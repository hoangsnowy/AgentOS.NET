// JsonExtractor runs on every JSON agent reply (LlmAgentBase: ExtractJson → Deserialize). Replies from the Coding agent
// carry whole files, so ~100 KB is normal; models wrap the JSON in a ```json fence or in prose about half the time.

using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.Json;
using AgentOs.Modules.Pipeline.Agents;
using BenchmarkDotNet.Attributes;

namespace AgentOs.Benchmarks.Text;

/// <summary>The shape of a Coding agent reply (files with their full content).</summary>
public sealed record CodeReplyDto(string ProjectName, string Architecture, IReadOnlyList<CodeReplyFile> Files, string? Notes);

/// <summary>One generated file.</summary>
public sealed record CodeReplyFile(string Path, string Content, string Language);

/// <summary><see cref="JsonExtractor"/> on large agent replies in the three shapes models produce.</summary>
[MemoryDiagnoser]
public class JsonExtractorBenchmarks
{
    private string _bare = null!;
    private string _fenced = null!;
    private string _prose = null!;

    /// <summary>A ~100 KB reply: 60 C# files of ~1.6 KB each.</summary>
    [GlobalSetup]
    public void Setup()
    {
        var files = new List<CodeReplyFile>(60);
        for (var i = 0; i < 60; i++)
        {
            var sb = new StringBuilder();
            sb.Append(CultureInfo.InvariantCulture, $"namespace Xiangqi.Core;\n\n/// <summary>Piece rules #{i}.</summary>\npublic sealed class Rule{i}\n{{\n");
            for (var m = 0; m < 12; m++)
            {
                sb.Append(CultureInfo.InvariantCulture, $"    public bool IsLegal{m}(Square from, Square to) => from.File != to.File && \"{m}\" != \"x\";\n");
            }
            sb.Append("}\n");
            files.Add(new CodeReplyFile($"src/Xiangqi.Core/Rules/Rule{i}.cs", sb.ToString(), "csharp"));
        }
        var dto = new CodeReplyDto("Xiangqi", "Clean architecture: Core (rules) → App (use cases) → Web (Blazor).", files, "Generated by the Coding agent.");
        _bare = JsonSerializer.Serialize(dto, JsonExtractor.DefaultOptions);
        _fenced = "Here is the implementation you asked for. I kept the rules in the core project.\n\n```json\n" + _bare + "\n```\n\nLet me know if you want the tests too.";
        _prose = "Sure — the complete project follows. " + _bare + " That covers every rule in the ticket.";
    }

    /// <summary>The reply is exactly the JSON object.</summary>
    [Benchmark(Baseline = true)]
    public string ExtractBare() => JsonExtractor.ExtractJson(_bare, "Coding");

    /// <summary>JSON inside a ```json fence with prose around it.</summary>
    [Benchmark]
    public string ExtractFenced() => JsonExtractor.ExtractJson(_fenced, "Coding");

    /// <summary>JSON embedded in prose with no fence.</summary>
    [Benchmark]
    public string ExtractProseWrapped() => JsonExtractor.ExtractJson(_prose, "Coding");

    /// <summary>The full agent path for a fenced reply: extract the payload, then deserialize it.</summary>
    [Benchmark]
    public CodeReplyDto AgentPathFenced() => JsonExtractor.Deserialize<CodeReplyDto>(JsonExtractor.ExtractJson(_fenced, "Coding"), "Coding");

    /// <summary>Deserialize straight from a fenced reply (TicketDecomposerAgent's path).</summary>
    [Benchmark]
    public CodeReplyDto DeserializeFenced() => JsonExtractor.Deserialize<CodeReplyDto>(_fenced, "Coding");
}
